"""Users, organisations, devices (spec sections 6, 25, 32, 51).

THE ROLE MODEL
--------------
Four roles, and the fourth is the one worth explaining:

* `STUDENT`  - owns their own data, belongs to no organisation
* `MANAGER`  - sees their organisation's aggregates
* `EMPLOYEE` - monitored, belongs to an organisation
* `DEVICE`   - **an installed agent, not a person**

A device credential can write its own events and read nothing about anybody. That
separation matters: a stolen device token should let an attacker post nonsense
telemetry, not browse an organisation's productivity records.

ENROLMENT TOKENS ARE STORED HASHED
----------------------------------
`Device.enrollment_token_hash` holds a hash, never the token. A manager sees the
token exactly once, when it is generated. If the database leaks, the tokens in it
cannot be used - the same reasoning as passwords, for the same reason.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import JSON, Boolean, DateTime, ForeignKey, Index, Integer, String, Text, true
from sqlalchemy.orm import Mapped, mapped_column, relationship

from focusguard_backend.models.base import Base, TimestampMixin


class Organization(Base, TimestampMixin):
    """A business using FocusGuard. The root of every tenant scope."""

    __tablename__ = "organizations"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    slug: Mapped[str] = mapped_column(String(80), unique=True, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    users: Mapped[list[User]] = relationship(back_populates="organization")
    devices: Mapped[list[Device]] = relationship(back_populates="organization")


class User(Base, TimestampMixin):
    """Anyone who can log in.

    Students and business users share this table because they share
    authentication; what differs is the role and whether an organisation is set.
    """

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(primary_key=True)
    email: Mapped[str] = mapped_column(String(320), unique=True, nullable=False)

    #: Argon2id. Never a plaintext or reversible value.
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    full_name: Mapped[str | None] = mapped_column(String(200))

    #: STUDENT, MANAGER, EMPLOYEE. DEVICE never appears here - a device is not a
    #: person and cannot log in.
    role: Mapped[str] = mapped_column(String(20), nullable=False, index=True)

    #: NULL for students, who belong to no organisation and are scoped by user_id.
    organization_id: Mapped[int | None] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), index=True
    )
    department_id: Mapped[int | None] = mapped_column(
        ForeignKey("departments.id", ondelete="SET NULL"), index=True
    )

    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    #: True unless the person signed themselves up and has not yet entered the
    #: code emailed to them. Accounts a manager creates, and every account that
    #: existed before verification was introduced, count as verified - so this
    #: is a state only self-registration can put an account in.
    email_verified: Mapped[bool] = mapped_column(
        Boolean, default=True, server_default=true(), nullable=False
    )
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    #: Employees: office hours set by the manager. On these weekdays (0 = Monday)
    #: at `work_start` ("HH:MM", the employee's own clock) the employee's
    #: computer starts a focus session by itself for `work_minutes`. The employee
    #: can close it; the manager is told and can ask for it to start again.
    work_days: Mapped[list | None] = mapped_column(JSON)
    work_start: Mapped[str | None] = mapped_column(String(5))
    work_minutes: Mapped[int | None] = mapped_column(Integer)

    organization: Mapped[Organization | None] = relationship(back_populates="users")
    devices: Mapped[list[Device]] = relationship(back_populates="user")

    __table_args__ = (Index("ix_users_org_role", "organization_id", "role"),)


class Department(Base, TimestampMixin):
    """A team within an organisation (spec section 24)."""

    __tablename__ = "departments"

    id: Mapped[int] = mapped_column(primary_key=True)
    organization_id: Mapped[int] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(120), nullable=False)


class Device(Base, TimestampMixin):
    """One installed agent (spec section 25).

    Events arrive attached to a device, not a user, so a person using two
    machines produces two attributable streams rather than one confused one.
    """

    __tablename__ = "devices"

    id: Mapped[int] = mapped_column(primary_key=True)

    #: Generated by the agent on first run and stable across restarts.
    device_uuid: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    device_name: Mapped[str] = mapped_column(String(200), nullable=False)

    #: NULL for a student's own machine, which belongs to no organisation.
    organization_id: Mapped[int | None] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), index=True
    )
    user_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), index=True
    )

    #: The enrolment token, hashed. A manager sees the token once, at creation.
    enrollment_token_hash: Mapped[str | None] = mapped_column(Text)

    #: Single-use and expiring (spec section 25). A token that never expired
    #: would sit in a chat log indefinitely, usable by anyone who found it.
    enrollment_expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    enrolled_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    #: The long-lived credential the agent uses after enrolment, hashed.
    #:
    #: Not a JWT: an agent runs unattended for months and cannot refresh a token
    #: on its own, so the credential must be revocable server-side. A row can be
    #: revoked; a signed claim cannot.
    secret_hash: Mapped[str | None] = mapped_column(String(64), index=True)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    agent_version: Mapped[str | None] = mapped_column(String(40))
    platform: Mapped[str | None] = mapped_column(String(60))

    #: Drives the "currently working / offline" board (spec section 26).
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), index=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    organization: Mapped[Organization | None] = relationship(back_populates="devices")
    user: Mapped[User | None] = relationship(back_populates="devices")


class PrivacyConsent(Base, TimestampMixin):
    """A record of what a user agreed to, and when (spec sections 25, 62).

    Kept as an append-only log rather than a flag on the user: a consent record
    that can be silently flipped is not evidence of anything, and an employee
    should be able to see exactly what they agreed to and on what date.
    """

    __tablename__ = "privacy_consents"

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    device_id: Mapped[int | None] = mapped_column(
        ForeignKey("devices.id", ondelete="SET NULL")
    )
    consent_version: Mapped[str] = mapped_column(String(20), nullable=False)
    granted_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
